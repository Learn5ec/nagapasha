class TokenBucket:
    """Token-bucket rate limiter."""

    def __init__(self, burst: int, refill_rate: float):
        self.burst = burst
        self.refill_rate = refill_rate
        self._tokens = float(burst)
        self._last = time.monotonic()

    def _refill(self):
        now = time.monotonic()
        elapsed = now - self._last
        self._last = now
        self._tokens = min(self.burst, self._tokens + elapsed * self.refill_rate)

    async def acquire(self):
        while True:
            self._refill()
            if self._tokens >= 1.0:
                self._tokens -= 1.0
                return
            wait = (1.0 - self._tokens) / self.refill_rate
            await asyncio.sleep(max(wait, 0.1))


@dataclass
class Delta:
    is_no_diff: bool = True
    status_delta: Optional[int] = None
    content_length_delta: int = 0
    response_time_delta: float = 0.0
    has_error: bool = False
    has_reflected: bool = False
    reflected_text: str = ""
    is_confirmed_hit: bool = False
    is_near_miss: bool = False


def compute_delta(status, body, elapsed):
    delta = Delta()

    # Status
    if status != BASELINE_STATUS:
        delta.status_delta = status - BASELINE_STATUS
        delta.is_no_diff = False

    # Content length
    cl_delta = len(body) - BASELINE_CONTENT_LENGTH
    if BASELINE_CONTENT_LENGTH > 0 and abs(cl_delta) / BASELINE_CONTENT_LENGTH > 0.10:
        delta.content_length_delta = cl_delta
        delta.is_no_diff = False

    # Response time
    if BASELINE_AVG_TIME > 0 and elapsed > BASELINE_AVG_TIME * 3:
        delta.response_time_delta = elapsed - BASELINE_AVG_TIME
        delta.is_no_diff = False

    # Error signatures
    error_sigs = [
        r"(?i)sql\s*(syntax|error|exception)",
        r"(?i)stack\s*trace",
        r"(?i)Traceback\s*\(",
        r"(?i)Fatal\s*error",
        r"(?i)permission\s*denied",
    ]
    for sig in error_sigs:
        if re.search(sig, body):
            delta.has_error = True
            delta.is_no_diff = False
            break

    # Reflected payload (checked in main loop)

    if delta.is_no_diff:
        return delta

    if delta.has_error:
        delta.is_confirmed_hit = True
    elif delta.status_delta is not None and delta.status_delta < 0:
        delta.is_near_miss = True
    elif delta.response_time_delta > 1.0:
        delta.is_near_miss = True

    return delta


