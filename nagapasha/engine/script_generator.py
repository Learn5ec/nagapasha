"""Phase 1 standalone script generator.

Generates a self-contained, executable Python script from the finalized
RequestModel. Zero LLM dependency — can be committed, rerun, regression-tested.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Optional

from nagapasha.models.request_model import RequestModel


def _sanitize_constant(value: Any) -> str:
    """Sanitize a value for embedding as a Python constant."""
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, (int, float)):
        return repr(value)
    if value is None:
        return "None"
    if isinstance(value, dict):
        items = ", ".join(
            f"{_sanitize_constant(k)}: {_sanitize_constant(v)}"
            for k, v in sorted(value.items())
        )
        return f"{{{items}}}"
    if isinstance(value, list):
        items = ", ".join(_sanitize_constant(v) for v in value)
        return f"[{items}]"
    # String: escape and quote
    return repr(str(value))


class StaticScriptGenerator:
    """Generates a standalone, executable Python script."""

    def generate(
        self, request_model: RequestModel, output_path: Optional[Path] = None
    ) -> Path:
        """Generate a standalone Python script.

        Args:
            request_model: The finalized RequestModel with attack specs.
            output_path: Where to write the script. If None, writes to
                         scripts/engagements/<id>/run_payloads.py.

        Returns:
            Path to the generated script.
        """
        if output_path is None:
            eid = request_model.engagement_id or "unknown"
            output_path = (
                Path("scripts") / "engagements" / eid / "run_payloads.py"
            )
            output_path.parent.mkdir(parents=True, exist_ok=True)

        # Render the template
        rendered = self._render(request_model)
        output_path.write_text(rendered)
        return output_path

    def _render(self, req: RequestModel) -> str:
        """Render the script template using simple string replacement."""
        jwt_info = req.jwt_info or {}
        rate_config = req.rate_limit_config or {}
        baseline = req.baseline_fingerprint or {}

        # Encode values safely
        encoded_headers = _sanitize_constant(req.headers)
        encoded_cookies = _sanitize_constant(req.cookies)

        # Rate limit config
        burst = rate_config.get("burst", 10)
        refill_rate = rate_config.get("refill_rate", 4.0)

        # JWT info
        jwt_expires_at = jwt_info.get("exp")
        jwt_alg = jwt_info.get("alg")
        jwt_flagged = jwt_info.get("algorithm_flagged", False)

        # Attack specs
        attacks = req.attack_specs
        encoded_attacks = _sanitize_constant(attacks)

        # SSL verification default (scripts use SSL verification by default)
        verify_ssl = req.verify_ssl if hasattr(req, "verify_ssl") and req.verify_ssl else True

        result = _SCRIPT_TEMPLATE

        # Replace placeholders (order matters for nested replacements)
        result = result.replace("{{ENGAGEMENT_ID}}", req.engagement_id or "unknown")
        result = result.replace("{{GENERATED_DATE}}", "2026-08-10")
        result = result.replace("{{METHOD}}", _sanitize_constant(req.method))
        result = result.replace("{{URL}}", _sanitize_constant(req.url))
        result = result.replace("{{BASE_URL}}", _sanitize_constant(req.base_url))
        result = result.replace("{{HEADERS}}", encoded_headers)
        result = result.replace("{{COOKIES}}", encoded_cookies)
        result = result.replace("{{RATE_LIMIT_BURST}}", str(int(burst)))
        result = result.replace("{{RATE_LIMIT_RATE}}", str(refill_rate))
        result = result.replace("{{VERIFY_SSL}}", str(verify_ssl))
        result = result.replace("{{JWT_EXPIRES_AT}}", str(jwt_expires_at))
        result = result.replace("{{JWT_ALG}}", repr(jwt_alg))
        result = result.replace("{{JWT_FLAGGED}}", str(jwt_flagged))
        result = result.replace("{{BASELINE_STATUS}}",
                                _sanitize_constant(baseline.get("status_code")))
        result = result.replace("{{BASELINE_CONTENT_LENGTH}}",
                                _sanitize_constant(baseline.get("content_length")))
        result = result.replace("{{BASELINE_BODY_HASH}}",
                                _sanitize_constant(baseline.get("body_hash")))
        result = result.replace("{{BASELINE_AVG_TIME}}",
                                _sanitize_constant(baseline.get("avg_response_time")))
        result = result.replace("{{ATTACKS}}", encoded_attacks)

        return result


