def build_request(base_url, method, headers, cookies,
                  param, placement, encoding, glue, payload):
    """Construct a request from a parameter, placement, and payload."""
    kwargs = {"headers": dict(headers), "cookies": dict(cookies)}

    if placement == "full_replace":
        # Replace the parameter value entirely
        if param and ("?" in base_url):
            new_url = _replace_query(base_url, param, payload)
        elif param and "/" in base_url:
            new_url = _replace_path(base_url, param, payload)
        else:
            new_url = base_url
        kwargs["url"] = new_url

    elif placement == "prefix":
        if param and ("?" in base_url):
            new_url = _prefix_query(base_url, param, glue, payload)
        else:
            new_url = base_url
        kwargs["url"] = new_url

    elif placement == "suffix":
        if param and ("?" in base_url):
            new_url = _suffix_query(base_url, param, glue, payload)
        else:
            new_url = base_url
        kwargs["url"] = new_url

    elif placement == "wrap":
        # Use glue as pre/post wrapper
        pre = glue.get("pre", "") if isinstance(glue, dict) else glue
        post = glue.get("post", "") if isinstance(glue, dict) else ""
        if isinstance(pre, str):
            pre = ""
        if isinstance(post, str):
            post = ""
        if param and ("?" in base_url):
            new_url = _wrap_query(base_url, param, pre, post, payload)
        else:
            new_url = base_url
        kwargs["url"] = new_url

    elif placement == "json_field_value":
        # Inject as a JSON field value — re-serialize the body
        kwargs["json"] = {param: payload}
        kwargs["headers"]["Content-Type"] = "application/json"

    elif placement == "header_value":
        # Inject as a header value
        kwargs["headers"][param] = payload
        kwargs["url"] = base_url

    else:
        kwargs["url"] = base_url

    return kwargs


def _replace_query(url, param, value):
    from urllib.parse import urlparse, parse_qs, urlencode, urlunparse
    parsed = urlparse(url)
    qs = parse_qs(parsed.query, keep_blank_values=True)
    qs[param] = [value]
    new_query = urlencode(qs, doseq=True)
    return urlunparse(parsed._replace(query=new_query))


def _replace_path(url, param, value):
    parts = url.split("/")
    for i, part in enumerate(parts):
        if part == param or (param and param in part):
            parts[i] = value
            break
    return "/".join(parts)


def _prefix_query(url, param, glue, value):
    from urllib.parse import urlparse, parse_qs, urlencode, urlunparse
    parsed = urlparse(url)
    qs = parse_qs(parsed.query, keep_blank_values=True)
    qs[param] = [glue + value]
    new_query = urlencode(qs, doseq=True)
    return urlunparse(parsed._replace(query=new_query))


def _suffix_query(url, param, glue, value):
    from urllib.parse import urlparse, parse_qs, urlencode, urlunparse
    parsed = urlparse(url)
    qs = parse_qs(parsed.query, keep_blank_values=True)
    qs[param] = [value + glue]
    new_query = urlencode(qs, doseq=True)
    return urlunparse(parsed._replace(query=new_query))


def _wrap_query(url, param, pre, post, value):
    from urllib.parse import urlparse, parse_qs, urlencode, urlunparse
    parsed = urlparse(url)
    qs = parse_qs(parsed.query, keep_blank_values=True)
    qs[param] = [pre + value + post]
    new_query = urlencode(qs, doseq=True)
    return urlunparse(parsed._replace(query=new_query))


